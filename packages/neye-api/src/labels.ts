export function neyeLabel(value?: null | string) {
  if (!value) return '未知状态';
  const label = labels[value];
  if (label) return label;
  if (import.meta.env.DEV) console.warn(`[NEye] 未配置中文状态词：${value}`);
  return '未知状态';
}

export function neyeStatusLabel(value?: null | string) {
  return neyeLabel(value);
}

export function neyeTypeLabel(value?: null | string) {
  return neyeLabel(value);
}
